"""Strict bounded validation for PNG handwriting evidence before storage.

Supports the non-interlaced 8-bit RGB/RGBA/gray PNG generated by the local
Wacom renderer and the synthetic controlled API test. Rejects malformed
chunks, CRC mismatches, trailing data, excessive dimensions, or inflated
IDAT streams. Never reads metadata into audit logs.
"""
from __future__ import annotations

import struct
import zlib

from fastapi import HTTPException

PNG_MAGIC = b"\x89PNG\r\n\x1a\n"
MAX_PNG_BYTES = 128_000
MAX_WIDTH = 2048
MAX_HEIGHT = 1024
_MAX_IDAT_INFLATED = 4_200_000


def _invalid() -> HTTPException:
    return HTTPException(status_code=422, detail="Invalid Wacom PNG capture")


def validate_wacom_png(data: bytes) -> None:
    if not isinstance(data, bytes) or not (32 <= len(data) <= MAX_PNG_BYTES):
        raise _invalid()
    if not data.startswith(PNG_MAGIC):
        raise _invalid()

    offset = len(PNG_MAGIC)
    seen_ihdr = seen_idat = seen_iend = False
    idat_closed = False
    width = height = row_bytes = 0
    compressed = bytearray()
    while offset < len(data):
        if len(data) - offset < 12:
            raise _invalid()
        size = struct.unpack_from(">I", data, offset)[0]
        kind = data[offset + 4:offset + 8]
        if size > MAX_PNG_BYTES or size > len(data) - offset - 12:
            raise _invalid()
        payload = data[offset + 8:offset + 8 + size]
        expected_crc = struct.unpack_from(">I", data, offset + 8 + size)[0]
        if zlib.crc32(kind + payload) & 0xffffffff != expected_crc:
            raise _invalid()
        offset += 12 + size

        if not seen_ihdr:
            if kind != b"IHDR" or size != 13:
                raise _invalid()
            width, height, depth, color, compression, filtering, interlace = struct.unpack(
                ">IIBBBBB", payload
            )
            channels = {0: 1, 2: 3, 4: 2, 6: 4}.get(color)
            if (
                not channels or depth != 8 or compression != 0
                or filtering != 0 or interlace != 0
                or not (1 <= width <= MAX_WIDTH and 1 <= height <= MAX_HEIGHT)
            ):
                raise _invalid()
            row_bytes = width * channels
            if (row_bytes + 1) * height > _MAX_IDAT_INFLATED:
                raise _invalid()
            seen_ihdr = True
        elif kind == b"IDAT":
            if idat_closed or seen_iend:
                raise _invalid()
            seen_idat = True
            compressed.extend(payload)
            if len(compressed) > MAX_PNG_BYTES:
                raise _invalid()
        elif kind == b"IEND":
            if size != 0 or not seen_idat or offset != len(data):
                raise _invalid()
            seen_iend = True
            break
        elif kind in (b"PLTE", b"tRNS", b"iCCP", b"eXIf", b"acTL", b"fcTL", b"fdAT"):
            # No palettes, embedded profile, metadata exfiltration or animation.
            raise _invalid()
        else:
            # Only known inert ancillary chunks are permitted.
            if kind not in (b"pHYs", b"gAMA", b"sRGB", b"cHRM"):
                raise _invalid()
            if seen_idat:
                idat_closed = True

    if not seen_ihdr or not seen_idat or not seen_iend:
        raise _invalid()
    try:
        decompressor = zlib.decompressobj()
        limit = (row_bytes + 1) * height
        decoded = decompressor.decompress(bytes(compressed), limit + 1)
        decoded += decompressor.flush(limit + 1 - len(decoded))
    except (zlib.error, ValueError) as error:
        raise _invalid() from error
    if (
        len(decoded) != limit or not decompressor.eof
        or decompressor.unused_data or decompressor.unconsumed_tail
        or any(decoded[index * (row_bytes + 1)] > 4 for index in range(height))
    ):
        raise _invalid()
