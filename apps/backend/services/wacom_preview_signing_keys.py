"""Fail-closed preview ticket key loading for Wacom workstation admissions.

A signing key is supplied only via deployment secret configuration.
Missing/malformed configuration prevents ticket issuance; no autogenerated
production signing keys or private material in browser assets.
"""
from __future__ import annotations

import base64
import binascii
import os
import re

from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey
from fastapi import HTTPException

_KEY_ID = re.compile(r"^[A-Za-z0-9_-]{1,64}$")


def load_wacom_preview_ticket_signer() -> tuple[Ed25519PrivateKey, str]:
    enabled = os.environ.get("LOANHUB_WACOM_PREVIEW_TICKETS_ENABLED")
    if enabled != "true":
        raise HTTPException(503, "Wacom physical preview authorization disabled")
    encoded = os.environ.get("LOANHUB_WACOM_PREVIEW_SIGNING_SEED_B64", "")
    key_id = os.environ.get("LOANHUB_WACOM_PREVIEW_SIGNING_KID", "")
    if not _KEY_ID.fullmatch(key_id):
        raise HTTPException(503, "Wacom signing key configuration unavailable")
    try:
        seed = base64.b64decode(encoded, validate=True)
    except (binascii.Error, ValueError) as error:
        raise HTTPException(503, "Wacom signing key configuration unavailable") from error
    if len(seed) != 32 or base64.b64encode(seed).decode("ascii") != encoded:
        raise HTTPException(503, "Wacom signing key configuration unavailable")
    return Ed25519PrivateKey.from_private_bytes(seed), key_id
