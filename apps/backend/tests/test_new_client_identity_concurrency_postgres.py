"""Opt-in isolated PostgreSQL concurrency and rollback contract tests.

These tests create/drop only uniquely named probe tables in a dedicated test
database. They NEVER query LoanHub customer, loan, borrower or payment tables.
Set LOANHUB_CLIENT_IDENTITY_TEST_POSTGRES_URL to an isolated disposable DB.
"""
from __future__ import annotations

from concurrent.futures import ThreadPoolExecutor
import os
from threading import Barrier
from uuid import uuid4

import pytest
from sqlalchemy import create_engine, text
from sqlalchemy.exc import IntegrityError
from sqlalchemy.orm import Session

from services.new_client_identity_locks import _identity_lock_keys

DSN_NAME = "LOANHUB_CLIENT_IDENTITY_TEST_POSTGRES_URL"


def _test_engine():
    dsn = os.environ.get(DSN_NAME)
    if not dsn:
        pytest.skip("Isolated identity PostgreSQL test DB not configured")
    engine = create_engine(dsn, pool_size=4, max_overflow=0, pool_pre_ping=True)
    if engine.dialect.name != "postgresql":
        engine.dispose()
        pytest.skip("Only PostgreSQL isolated tests supported")
    return engine


def _create_probe(engine, table):
    # Table name is generated from uuid4 hex, never supplied by an operator.
    with engine.begin() as connection:
        connection.execute(text(f"""
            CREATE TABLE {table} (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                national_id text NOT NULL, phone text NOT NULL,
                source text NOT NULL DEFAULT 'new',
                UNIQUE (national_id),
                UNIQUE (phone)
            )
        """))
        connection.execute(text(
            f"CREATE UNIQUE INDEX {table}_identity_normalized "
            f"ON {table} (lower(btrim(national_id)))"
        ))
        connection.execute(text(
            f"CREATE UNIQUE INDEX {table}_phone_normalized "
            f"ON {table} (lower(btrim(phone)))"
        ))


def _drop_probe(engine, table):
    with engine.begin() as connection:
        connection.execute(text(f"DROP TABLE IF EXISTS {table}"))


def test_two_branches_same_identity_serialize_with_one_synthetic_row():
    engine = _test_engine()
    table = f"client_identity_probe_{uuid4().hex[:16]}"
    gate = Barrier(2)
    try:
        _create_probe(engine, table)

        def worker(branch_label: str, national_id: str, phone: str):
            keys = _identity_lock_keys(
                national_id=national_id, passport_number=None,
                phone=phone, email=None)
            gate.wait(timeout=15)
            with Session(engine) as db:
                with db.begin():
                    for identity_key in keys:
                        db.execute(text(
                            "SELECT pg_advisory_xact_lock("
                            "hashtextextended(:identity_key, 0))"
                        ), {"identity_key": identity_key})
                    existing = db.execute(text(
                        f"SELECT id FROM {table} "
                        "WHERE lower(btrim(national_id))=lower(btrim(:national_id))"
                    ), {"national_id": national_id}).scalar_one_or_none()
                    if existing is not None:
                        return existing, False
                    record_id = db.execute(text(
                        f"INSERT INTO {table} (national_id, phone, source) "
                        "VALUES (:national_id, :phone, :source) RETURNING id"
                    ), {"national_id": national_id, "phone": phone,
                        "source": branch_label}).scalar_one()
                    return record_id, True

        with ThreadPoolExecutor(max_workers=2) as pool:
            a = pool.submit(worker, "branch-a", " SYN-ABC ", "59000000")
            b = pool.submit(worker, "branch-b", "syn-abc", " 59000000 ")
            results = [a.result(timeout=25), b.result(timeout=25)]
        assert len({result[0] for result in results}) == 1
        assert sum(result[1] for result in results) == 1
        with engine.connect() as db:
            assert db.execute(text(f"SELECT count(*) FROM {table}")).scalar_one() == 1
    finally:
        try:
            _drop_probe(engine, table)
        finally:
            engine.dispose()


def test_normalized_unique_index_enforces_conflict_and_savepoint_rollback():
    engine = _test_engine()
    table = f"client_identity_probe_{uuid4().hex[:16]}"
    try:
        _create_probe(engine, table)
        with engine.begin() as connection:
            connection.execute(text(
                f"INSERT INTO {table} (national_id, phone, source) "
                "VALUES (' EXISTING ', '59000001', 'historical-synthetic')"
            ))
            # A failed registration stays inside a savepoint. The historical
            # synthetic row is not changed and the transaction remains usable.
            with pytest.raises(IntegrityError):
                with connection.begin_nested():
                    connection.execute(text(
                        f"INSERT INTO {table} (national_id, phone, source) "
                        "VALUES ('existing', '59000002', 'new-attempt')"
                    ))
            assert connection.execute(text(
                f"SELECT count(*) FROM {table}"
            )).scalar_one() == 1
            assert connection.execute(text(
                f"SELECT source FROM {table}"
            )).scalar_one() == "historical-synthetic"
    finally:
        try:
            _drop_probe(engine, table)
        finally:
            engine.dispose()
